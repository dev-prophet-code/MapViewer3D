function readLang() {
  const q = params.get('lang');
  if (q && STRINGS[q]) return q;
  try {
    const l = localStorage.getItem(STORAGE_KEY);
    if (l && STRINGS[l]) return l;
  } catch { /* ohne Speicher: Standard */ }
  return 'en';
}

export const lang = readLang();

// Text zum Schlüssel, {name}-Platzhalter werden ersetzt; fehlt er, gilt Englisch.
export function t(key, vars = {}) {
  const s = STRINGS[lang][key] ?? STRINGS.en[key] ?? key;
  return s.replace(/\{(\w+)\}/g, (_, k) => (vars[k] ?? ''));
}

export function setLang(l) {
  if (!STRINGS[l] || l === lang) return;
  try { localStorage.setItem(STORAGE_KEY, l); } catch { /* nur für diese Sitzung */ }
  location.reload();
}

// Statische Texte der Seite übersetzen und die Sprachauswahl füllen
export function applyStatic() {
  document.documentElement.lang = lang;
  for (const el of document.querySelectorAll('[data-i18n]')) el.textContent = t(el.dataset.i18n);
  for (const el of document.querySelectorAll('[data-i18n-html]')) el.innerHTML = t(el.dataset.i18nHtml);
  for (const el of document.querySelectorAll('[data-i18n-ph]')) el.placeholder = t(el.dataset.i18nPh);
  for (const el of document.querySelectorAll('[data-i18n-title]')) {
    el.title = t(el.dataset.i18nTitle);
    if (!el.textContent.trim() || el.classList.contains('hud-btn')) el.setAttribute('aria-label', el.title);
  }
  for (const el of document.querySelectorAll('[data-i18n-aria]')) el.setAttribute('aria-label', t(el.dataset.i18nAria));
  const sel = document.getElementById('lang');
  if (sel) {
    sel.replaceChildren(...Object.entries(LANGUAGES).map(([k, v]) => new Option(v, k)));
    sel.value = lang;
    sel.onchange = () => setLang(sel.value);
  }
}
